function safeHref(url) {
  // Remediation links come from repository code, but never render a
  // non-HTTP(S) URL such as javascript: as a link target.
  return typeof url === "string" && /^https?:\/\//i.test(url) ? url : undefined;
}

function Status({ map, status, wrapText }) {
  const entry = map[status] || { type: "info", label: status };
  return (
    <StatusIndicator type={entry.type} wrapText={wrapText}>
      {entry.label}
    </StatusIndicator>
  );
}

function Section({ id, children }) {
  return (
    <section id={id} className="report-section" style={{ scrollMarginTop: 72 }}>
      {children}
    </section>
  );
}

function sectionsFor(data) {
  const sections = [
    { id: "overview", text: "Assessment Overview" },
    { id: "maturity", text: "Maturity Progress" },
    { id: "capabilities", text: "Capability Coverage" },
    { id: "checks", text: "Check Results" },
  ];
  if (data.delegated_admins.length) {
    sections.push({ id: "delegated-admins", text: "Delegated Administrators" });
  }
  if (data.maturity.scoring_model) {
    sections.push({ id: "methodology", text: "Maturity Methodology" });
  }
  return sections;
}

function useActiveSection(sections) {
  const [active, setActive] = useState(sections[0].id);
  useEffect(() => {
    if (typeof IntersectionObserver === "undefined") {
      return undefined;
    }
    const observer = new IntersectionObserver(
      (entries) => {
        const visible = entries
          .filter((entry) => entry.isIntersecting)
          .sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top);
        if (visible.length) {
          setActive(visible[0].target.id);
        }
      },
      { rootMargin: "-10% 0px -75% 0px" },
    );
    sections.forEach(({ id }) => {
      const element = document.getElementById(id);
      if (element) {
        observer.observe(element);
      }
    });
    return () => observer.disconnect();
  }, [sections]);
  return [active, setActive];
}

