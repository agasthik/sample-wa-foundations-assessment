function Methodology({ model }) {
  return (
    <Container header={<Header variant="h2">Maturity Methodology</Header>}>
      <SpaceBetween size="l">
        <Box>
          {model.rule} {model.weight_note}
        </Box>
        {model.levels.map((level) => (
          <ExpandableSection
            key={level.level}
            variant="container"
            defaultExpanded
            headerText={`Level ${level.level} — ${level.name}`}
            headerCounter={
              level.criteria_count
                ? `(${level.complete_count}/${level.criteria_count} complete)`
                : "(Baseline level)"
            }
            headerDescription={level.description}
          >
            {level.criteria && level.criteria.length > 0 ? (
              <List
                ariaLabel={`Level ${level.level} criteria`}
                items={level.criteria}
                renderItem={(criterion) => ({
                  id: criterion.name,
                  content: criterion.name,
                  secondaryContent: criterion.detail,
                  actions: <Status map={CRITERION_STATUS} status={criterion.status} />,
                })}
              />
            ) : (
              <Box color="text-body-secondary">
                No additional criteria for this level.
              </Box>
            )}
          </ExpandableSection>
        ))}
      </SpaceBetween>
    </Container>
  );
}

export function initialMode() {
  return typeof window !== "undefined" &&
    window.matchMedia &&
    window.matchMedia("(prefers-color-scheme: dark)").matches
    ? Mode.Dark
    : Mode.Light;
}

export default function App({ data }) {
  const sections = useMemo(() => sectionsFor(data), [data]);
  const [activeSection, setActiveSection] = useActiveSection(sections);
  const [mode, setMode] = useState(initialMode);
  const [navigationOpen, setNavigationOpen] = useState(true);

  useEffect(() => {
    applyMode(mode);
  }, [mode]);

  const isDark = mode === Mode.Dark;
  const accountInfo = data.account_info;

  return (
    <>
      <div id="wafa-top-nav" style={{ position: "sticky", top: 0, zIndex: 1002 }}>
        <TopNavigation
          identity={{ href: "#overview", title: "Well-Architected Foundations Assessment" }}
          utilities={[
            {
              type: "button",
              iconSvg: isDark ? SUN_ICON : MOON_ICON,
              ariaLabel: isDark ? "Switch to light mode" : "Switch to dark mode",
              title: isDark ? "Light mode" : "Dark mode",
              onClick: () => setMode(isDark ? Mode.Light : Mode.Dark),
            },
          ]}
        />
      </div>
      <AppLayout
        headerSelector="#wafa-top-nav"
        toolsHide
        navigationOpen={navigationOpen}
        onNavigationChange={({ detail }) => setNavigationOpen(detail.open)}
        ariaLabels={{
          navigation: "Report sections",
          navigationToggle: "Open report sections",
          navigationClose: "Close report sections",
        }}
        navigation={
          <SideNavigation
            header={{ text: "Report sections", href: "#overview" }}
            activeHref={`#${activeSection}`}
            onFollow={(event) => {
              event.preventDefault();
              const id = event.detail.href.slice(1);
              setActiveSection(id);
              const element = document.getElementById(id);
              if (element) {
                element.scrollIntoView({ behavior: "smooth", block: "start" });
              }
            }}
            items={sections.map((section) => ({
              type: "link",
              text: section.text,
              href: `#${section.id}`,
            }))}
          />
        }
        content={
          <ContentLayout
            header={
              <Header
                variant="h1"
                description={`Account: ${accountInfo.account_id || "N/A"} (${accountInfo.account_type || "N/A"})`}
              >
                Well-Architected Foundations Assessment Report
              </Header>
            }
          >
            <SpaceBetween size="l">
              <Section id="overview">
                <Overview data={data} />
              </Section>
              <Section id="maturity">
                <MaturityProgress maturity={data.maturity} />
              </Section>
              <Section id="capabilities">
                <CapabilityCoverage axes={data.axis_scores} />
              </Section>
              <Section id="checks">
                <CheckResults checks={data.checks} summary={data.summary} />
              </Section>
              {data.delegated_admins.length > 0 && (
                <Section id="delegated-admins">
                  <DelegatedAdmins admins={data.delegated_admins} />
                </Section>
              )}
              {data.maturity.scoring_model && (
                <Section id="methodology">
                  <Methodology model={data.maturity.scoring_model} />
                </Section>
              )}
              <ReportFooter />
            </SpaceBetween>
          </ContentLayout>
        }
      />
    </>
  );
}
