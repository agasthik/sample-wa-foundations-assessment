function Counter({ label, value, status }) {
  return (
    <div>
      <Box variant="awsui-key-label">
        {status ? (
          <StatusIndicator type={CHECK_STATUS[status].type}>{label}</StatusIndicator>
        ) : (
          label
        )}
      </Box>
      <Box variant="awsui-value-large">{value}</Box>
    </div>
  );
}

// Five horizontal steps do not fit a phone-width viewport.
const NARROW_QUERY = "(max-width: 688px)";

function useIsNarrow() {
  const query = useMemo(
    () =>
      typeof window !== "undefined" && window.matchMedia
        ? window.matchMedia(NARROW_QUERY)
        : null,
    [],
  );
  const [isNarrow, setIsNarrow] = useState(query ? query.matches : false);
  useEffect(() => {
    if (!query) {
      return undefined;
    }
    const onChange = (event) => setIsNarrow(event.matches);
    query.addEventListener("change", onChange);
    return () => query.removeEventListener("change", onChange);
  }, [query]);
  return isNarrow;
}

function MaturityProgress({ maturity }) {
  const levels = maturity.scoring_model ? maturity.scoring_model.levels : [];
  const isNarrow = useIsNarrow();
  return (
    <Container header={<Header variant="h2">Maturity Progress</Header>}>
      <SpaceBetween size="l">
        {levels.length > 0 && (
          <Steps
            orientation={isNarrow ? "vertical" : "horizontal"}
            ariaLabel="Maturity level progression"
            steps={levels.map((level) => {
              const state = LEVEL_STATE[level.state] || LEVEL_STATE.later;
              return {
                status: state.type,
                statusIconAriaLabel: state.label,
                header: `Level ${level.level} — ${level.name}`,
                details: (
                  <SpaceBetween size="xxs">
                    <Box fontWeight="bold">{state.label}</Box>
                    <Box color="text-body-secondary">
                      {level.criteria_count
                        ? `${level.complete_count}/${level.criteria_count} criteria`
                        : "Baseline"}
                    </Box>
                  </SpaceBetween>
                ),
              };
            })}
          />
        )}
        {maturity.next_level ? (
          <SpaceBetween size="m">
            <ProgressBar
              value={maturity.next_level_progress}
              label={`Progress toward Level ${maturity.next_level}`}
            />
            {maturity.next_level_checks_needed &&
              maturity.next_level_checks_needed.length > 0 && (
                <SpaceBetween size="xs">
                  <Header variant="h3">Next steps (highest impact first)</Header>
                  <List
                    tagOverride="ol"
                    ariaLabel="Next steps"
                    items={maturity.next_level_checks_needed.slice(0, 5)}
                    renderItem={(name) => ({ id: name, content: name })}
                  />
                </SpaceBetween>
              )}
          </SpaceBetween>
        ) : (
          <Alert type="success">All Phase 1 criteria met.</Alert>
        )}
      </SpaceBetween>
    </Container>
  );
}

function CapabilityCoverage({ axes }) {
  const gaps = axes.filter((axis) => axis.check_count === 0);
  return (
    <Container
      header={
        <Header
          variant="h2"
          description="Percentage of mapped checks that are complete for each WA Foundations capability."
        >
          Capability Coverage (WA Foundations)
        </Header>
      }
    >
      <SpaceBetween size="m">
        <BarChart
          ariaLabel="WA Foundations capability coverage"
          horizontalBars
          hideFilter
          hideLegend
          height={320}
          xScaleType="categorical"
          yDomain={[0, 100]}
          xTitle="Capability"
          yTitle="Coverage (%)"
          series={[
            {
              title: "Coverage",
              type: "bar",
              data: axes.map((axis) => ({ x: axis.name, y: axis.score })),
              valueFormatter: (value) => `${value}%`,
            },
          ]}
        />
        {gaps.length > 0 && (
          <Box color="text-body-secondary" fontSize="body-s">
            {gaps.map((axis) => axis.name).join(", ")}: no Phase 1 checks are
            mapped to this capability yet, so it reports 0% coverage.
          </Box>
        )}
      </SpaceBetween>
    </Container>
  );
}

const STATUS_FILTERS = [
  { id: "all", text: "All" },
  { id: "complete", text: "Complete" },
  { id: "incomplete", text: "Incomplete" },
  { id: "error", text: "Errors" },
];

function CheckResults({ checks, summary }) {
  const [statusFilter, setStatusFilter] = useState("all");
  const counts = {
    all: summary.total,
    complete: summary.complete,
    incomplete: summary.incomplete,
    error: summary.errors,
  };
  const statusItems = useMemo(
    () =>
      statusFilter === "all"
        ? checks
        : checks.filter((check) => check.status === statusFilter),
    [checks, statusFilter],
  );
  const { items, collectionProps, filterProps, filteredItemsCount, paginationProps } =
    useCollection(statusItems, {
      filtering: {
        fields: ["check", "description", "status", "error"],
        empty: <Box textAlign="center">No checks with this status.</Box>,
        noMatch: <Box textAlign="center">No checks match the filter.</Box>,
      },
      sorting: {},
      pagination: { pageSize: 50 },
    });

  return (
    <SpaceBetween size="l">
      <Container
        header={
          <Header
            variant="h2"
            description="Only Complete results contribute to completion and capability scores. Incomplete and Error results do not satisfy maturity criteria. An Error does not necessarily mean the configuration is incorrect."
          >
            Check Results
          </Header>
        }
      >
        <div aria-label="Check result status definitions" role="group">
          <ColumnLayout columns={3} borders="vertical">
            <SpaceBetween size="xxs">
              <Status map={CHECK_STATUS} status="complete" />
              <Box>Verified and meets the criterion.</Box>
            </SpaceBetween>
            <SpaceBetween size="xxs">
              <Status map={CHECK_STATUS} status="incomplete" />
              <Box>Verified but does not meet the criterion.</Box>
            </SpaceBetween>
            <SpaceBetween size="xxs">
              <Status map={CHECK_STATUS} status="error" />
              <Box>
                Could not be reliably assessed, usually because of permissions
                or an AWS API failure.
              </Box>
            </SpaceBetween>
          </ColumnLayout>
        </div>
      </Container>
      <Table
        {...collectionProps}
        variant="container"
        ariaLabels={{ tableLabel: "Check results" }}
        header={
          <Header
            variant="h3"
            counter={`(${checks.length})`}
            actions={
              <SegmentedControl
                label="Filter by status"
                selectedId={statusFilter}
                onChange={({ detail }) => setStatusFilter(detail.selectedId)}
                options={STATUS_FILTERS.map((option) => ({
                  id: option.id,
                  text: `${option.text} (${counts[option.id]})`,
                }))}
              />
            }
          >
            Checks
          </Header>
        }
        filter={
          <TextFilter
            {...filterProps}
            filteringPlaceholder="Find checks"
            filteringAriaLabel="Filter checks"
            countText={`${filteredItemsCount} ${filteredItemsCount === 1 ? "match" : "matches"}`}
          />
        }
        pagination={<Pagination {...paginationProps} />}
        wrapLines
        items={items}
        columnDefinitions={[
          {
            // Fixed widths on the other columns leave the remaining space to
            // the wrapping Check column, so status labels stay on one line
            // even with the report sections navigation open.
            id: "check",
            header: "Check",
            sortingField: "check",
            isRowHeader: true,
            cell: (check) => (
              <SpaceBetween size="xxxs">
                <Box fontWeight="bold">{check.check}</Box>
                <Box color="text-body-secondary" fontSize="body-s">
                  {check.description}
                </Box>
                {check.error && (
                  <Box color="text-status-error" fontSize="body-s">
                    {check.error}
                  </Box>
                )}
              </SpaceBetween>
            ),
          },
          {
            id: "status",
            width: 150,
            header: "Status",
            sortingField: "status",
            // Long AWS error text in the Check column must not squeeze the
            // status label into a mid-word wrap.
            cell: (check) => (
              <Status map={CHECK_STATUS} status={check.status} wrapText={false} />
            ),
          },
          {
            id: "required",
            width: 120,
            header: "Required",
            sortingField: "required",
            cell: (check) => (check.required ? "Yes" : "No"),
          },
          {
            id: "loe",
            header: "LoE",
            width: 80,
            sortingField: "loe",
            cell: (check) => check.loe,
          },
          {
            id: "remediation",
            width: 130,
            header: "Remediation",
            cell: (check) =>
              safeHref(check.remediationLink) ? (
                <Link
                  external
                  href={safeHref(check.remediationLink)}
                  ariaLabel={`Remediation guidance for ${check.check}`}
                >
                  Fix
                </Link>
              ) : (
                "—"
              ),
          },
        ]}
      />
    </SpaceBetween>
  );
}

